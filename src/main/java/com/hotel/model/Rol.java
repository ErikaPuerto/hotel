package com.hotel.model;

public class Rol {

    private Integer idRol;

    private String nombre;

    // GETTERS

    public Integer getIdRol() {
        return idRol;
    }

    public String getNombre() {
        return nombre;
    }

    // SETTERS

    public void setIdRol(Integer idRol) {
        this.idRol = idRol;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }
}